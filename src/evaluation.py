"""Post-hoc evaluation against the SYNTHETIC ground truth.

This module is called only AFTER validation, matching and growth estimation have finished. The
ground-truth file is never passed to those stages. Metrics measure performance on fictional data
generated by src/synthetic_data.py and do not establish real-world accuracy.
"""

from __future__ import annotations

import numpy as np
import pandas as pd


def evaluate_matching(tracks: pd.DataFrame, gt: pd.DataFrame, run_a: str, run_b: str) -> dict:
    key = {(r.run_id, r.observation_id): (r.true_defect_id, r.record_kind) for r in gt.itertuples()}

    def tid(run, obs):
        return key.get((run, obs), (None, None))

    # true pairs: same real defect reported (non-duplicate) in both runs
    g = gt[gt["record_kind"].isin(["TRUE", "CORRUPTED"]) & (gt["true_defect_id"] != "NONE")]
    in_a = set(g.loc[g["run_id"] == run_a, "true_defect_id"])
    in_b = set(g.loc[g["run_id"] == run_b, "true_defect_id"])
    true_pairs = in_a & in_b

    res = {}
    for label, statuses in (("likely", ["LIKELY_MATCH"]), ("ambiguous", ["AMBIGUOUS"]),
                            ("all_assigned", ["LIKELY_MATCH", "AMBIGUOUS"])):
        sub = tracks[tracks["match_status"].isin(statuses)]
        correct = [tid(run_a, a)[0] == tid(run_b, b)[0] and tid(run_a, a)[0] not in (None, "NONE")
                   for a, b in zip(sub["obs_a"], sub["obs_b"])]
        n, c = len(sub), int(np.sum(correct))
        res[label] = dict(predicted_pairs=n, correct=c, false_matches=n - c,
                          precision=c / n if n else np.nan)
    allc = res["all_assigned"]["correct"]
    res["true_pairs"] = len(true_pairs)
    res["recall_all_assigned"] = allc / len(true_pairs) if true_pairs else np.nan
    res["recall_likely_only"] = res["likely"]["correct"] / len(true_pairs) if true_pairs else np.nan
    res["missed_true_pairs"] = len(true_pairs) - allc

    new = tracks[tracks["match_status"] == "NEW_LATER"]
    truly_new = [tid(run_b, b)[0] not in in_a for b in new["obs_b"]]
    res["new_later"] = dict(count=len(new), truly_absent_in_earlier_run=int(np.sum(truly_new)),
                            precision=float(np.mean(truly_new)) if len(new) else np.nan)
    unm = tracks[tracks["match_status"] == "UNMATCHED_EARLIER"]
    truly_unm = [tid(run_a, a)[0] not in in_b for a in unm["obs_a"]]
    res["unmatched_earlier"] = dict(count=len(unm), truly_absent_in_later_run=int(np.sum(truly_unm)),
                                    precision=float(np.mean(truly_unm)) if len(unm) else np.nan)
    return res


def evaluate_growth(growth: pd.DataFrame, gt: pd.DataFrame, run_a: str, run_b: str, k: float = 2.0) -> dict:
    """Rate error on correctly matched LIKELY pairs with valid depths and known uncertainty."""
    key = {(r.run_id, r.observation_id): r for r in gt.itertuples()}
    rows = []
    for r in growth[growth["match_status"] == "LIKELY_MATCH"].itertuples():
        ga, gb = key.get((run_a, r.obs_a)), key.get((run_b, r.obs_b))
        if ga is None or gb is None or ga.true_defect_id != gb.true_defect_id or ga.true_defect_id == "NONE":
            continue
        if not (np.isfinite(r.rate_mm_per_yr) and np.isfinite(r.sigma_rate_mm_per_yr)):
            continue
        rows.append(dict(true=ga.true_rate_mm_per_yr, base=r.rate_mm_per_yr, sig=r.sigma_rate_mm_per_yr,
                         shr=r.shrunk_rate_mm_per_yr, shr_sig=r.shrunk_sigma_mm_per_yr))
    E = pd.DataFrame(rows)
    if E.empty:
        return {"n": 0}

    def m(est):
        e = E[est] - E["true"]
        return dict(mae=float(np.mean(np.abs(e))), rmse=float(np.sqrt(np.mean(e ** 2))), bias=float(np.mean(e)))

    out = {"n": len(E), "baseline": m("base"), "shrinkage": m("shr"),
           "baseline_interval_coverage": float(np.mean(np.abs(E["base"] - E["true"]) <= k * E["sig"])),
           "shrinkage_interval_coverage": float(np.mean(np.abs(E["shr"] - E["true"]) <= k * E["shr_sig"])),
           "k": k}
    out["better_model"] = "shrinkage" if out["shrinkage"]["rmse"] < out["baseline"]["rmse"] else "baseline"
    return out
